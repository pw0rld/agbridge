#!/usr/bin/env bash
# agbridge gateway provisioning script.
#
# Generates a self-signed cert, writes gateway.yaml, installs a systemd
# unit, and starts the service. Idempotent: re-running preserves existing
# cert/config unless --force-* flags are passed.
#
# Usage:
#   sudo bash gateway-setup.sh --domain agbridge.example.com
#   sudo bash gateway-setup.sh --domain agbridge.example.com --port 8443
#
# Or via curl pipe:
#   curl -sSL https://github.com/pw0rld/agbridge/raw/main/scripts/gateway-setup.sh \
#     | sudo bash -s -- --domain agbridge.example.com
#
# Flags:
#   --domain HOST       Public hostname (required, used in cert CN + public_url)
#   --port  N           Listen port (default 443)
#   --config-dir DIR    Where to write cert + gateway.yaml (default /etc/agbridge)
#   --no-systemd        Skip systemd unit install (config + cert only)
#   --force-cert        Regenerate cert even if cert.pem already exists
#   --force-config      Overwrite gateway.yaml even if it exists
set -euo pipefail

DOMAIN=""
PORT="443"
CONFIG_DIR="/etc/agbridge"
STATE_DIR="/var/lib/agbridge"
LOG_DIR="/var/log/agbridge"
NO_SYSTEMD=false
FORCE_CERT=false
FORCE_CONFIG=false

usage() {
  sed -n '2,21p' "$0"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain) DOMAIN="$2"; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    --config-dir) CONFIG_DIR="$2"; shift 2 ;;
    --no-systemd) NO_SYSTEMD=true; shift ;;
    --force-cert) FORCE_CERT=true; shift ;;
    --force-config) FORCE_CONFIG=true; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "gateway-setup: unknown arg: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [[ -z "$DOMAIN" ]]; then
  echo "gateway-setup: --domain required" >&2
  exit 2
fi

if [[ "$(id -u)" -ne 0 ]]; then
  echo "gateway-setup: needs root (writes /etc /var/log /etc/systemd)" >&2
  exit 1
fi

# 1. Install agbridge binary if missing.
if ! command -v agbridge >/dev/null 2>&1; then
  echo "[*] agbridge not found, installing via install.sh"
  curl -sSL https://github.com/pw0rld/agbridge/raw/main/scripts/install.sh | bash
fi
agbridge --help >/dev/null 2>&1 || {
  echo "gateway-setup: agbridge binary broken" >&2
  exit 1
}

# 2. Create state/log/config dirs.
mkdir -p "$CONFIG_DIR" "$STATE_DIR" "$LOG_DIR"
chmod 700 "$CONFIG_DIR"

# 3. Generate cert (or skip if exists).
if [[ -f "$CONFIG_DIR/cert.pem" && "$FORCE_CERT" == false ]]; then
  echo "[*] $CONFIG_DIR/cert.pem exists, keeping (use --force-cert to regen)"
else
  echo "[*] generating self-signed cert for $DOMAIN"
  agbridge cert gen --cn "$DOMAIN" --out "$CONFIG_DIR"
fi

PIN=""
if [[ -f "$CONFIG_DIR/pin.txt" ]]; then
  PIN="$(cat "$CONFIG_DIR/pin.txt")"
fi

# 4. Write gateway.yaml.
PUBLIC_URL_SUFFIX=""
if [[ "$PORT" != "443" ]]; then
  PUBLIC_URL_SUFFIX=":$PORT"
fi

if [[ -f "$CONFIG_DIR/gateway.yaml" && "$FORCE_CONFIG" == false ]]; then
  echo "[*] $CONFIG_DIR/gateway.yaml exists, keeping (use --force-config to overwrite)"
else
  cat > "$CONFIG_DIR/gateway.yaml" <<EOF
# Generated by gateway-setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
listen: 0.0.0.0:$PORT
public_url: wss://$DOMAIN$PUBLIC_URL_SUFFIX/
audit_path: $LOG_DIR/audit.jsonl
audit_max_bytes: 67108864
audit_max_backups: 5
agents: []
daemons: []
EOF
  chmod 600 "$CONFIG_DIR/gateway.yaml"
  echo "[*] wrote $CONFIG_DIR/gateway.yaml"
fi

# 5. systemd unit.
if [[ "$NO_SYSTEMD" == true ]]; then
  echo "[*] --no-systemd set, skipping service install"
else
  CAP_LINES=""
  if [[ "$PORT" -lt 1024 ]]; then
    CAP_LINES="AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE"
  fi

  cat > /etc/systemd/system/agbridge.service <<EOF
[Unit]
Description=agbridge gateway
Documentation=https://github.com/pw0rld/agbridge
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=/usr/local/bin/agbridge gateway --config $CONFIG_DIR/gateway.yaml --cert $CONFIG_DIR/cert.pem --key $CONFIG_DIR/key.pem
ExecReload=/bin/kill -HUP \$MAINPID
Restart=on-failure
RestartSec=3
$CAP_LINES
DynamicUser=true
StateDirectory=agbridge
LogsDirectory=agbridge
ConfigurationDirectory=agbridge
ReadWritePaths=$LOG_DIR $STATE_DIR $CONFIG_DIR
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable --now agbridge
  sleep 2
  if ! systemctl is-active --quiet agbridge; then
    echo "[!] agbridge service failed to start; recent log:" >&2
    journalctl -u agbridge -n 30 --no-pager >&2
    exit 1
  fi
  echo "[*] agbridge.service active"
fi

# 6. Summary.
PUBLIC_URL="wss://$DOMAIN$PUBLIC_URL_SUFFIX/"
cat <<EOF

============================================
agbridge gateway ready.

  Domain:      $DOMAIN
  Port:        $PORT
  Public URL:  $PUBLIC_URL
  Cert pin:    ${PIN:-(see $CONFIG_DIR/pin.txt)}
  Config:      $CONFIG_DIR/gateway.yaml

Verify from another machine:
  echo | openssl s_client -connect $DOMAIN:$PORT -servername $DOMAIN 2>/dev/null \\
    | openssl x509 -fingerprint -sha256 -noout
  # fingerprint should match the pin above

Issue a daemon token (run on this gateway host):
  sudo agbridge issue-token --config $CONFIG_DIR/gateway.yaml \\
    --role=daemon --name=lab01 --allowed-paths=/home/me/projects

Service control:
  sudo systemctl status agbridge
  sudo systemctl reload agbridge      # re-reads gateway.yaml + gateway-state.json
  sudo journalctl -u agbridge -f
============================================
EOF
